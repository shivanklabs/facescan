EVENT_MATCH = "event_id = nullif(current_setting('app.event_id', true), '')::uuid"
SCOPE = "coalesce(current_setting('app.scope', true), '')"


def _enable_row_level_security() -> None:
    """Purpose: RLS on every event-scoped table, the scope policies and the audit trigger."""
    for table in EVENT_SCOPED_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        op.execute(
            f"CREATE POLICY {table}_event_isolation ON {table} "
            f"USING ({EVENT_MATCH}) WITH CHECK ({EVENT_MATCH})"
        )
    op.execute(f"CREATE POLICY events_admin_read ON events FOR SELECT USING ({SCOPE} = 'admin')")
    op.execute(
        f"CREATE POLICY audit_log_admin ON audit_log "
        f"USING ({SCOPE} = 'admin' AND event_id IS NULL) "
        f"WITH CHECK ({SCOPE} = 'admin' AND event_id IS NULL)"
    )
    op.execute(f"CREATE POLICY jobs_dispatch_read ON jobs FOR SELECT USING ({SCOPE} = 'dispatch')")
    op.execute(
        f"CREATE POLICY jobs_dispatch_update ON jobs FOR UPDATE "
        f"USING ({SCOPE} = 'dispatch') WITH CHECK ({SCOPE} = 'dispatch')"
    )
    op.execute(
        """
        CREATE FUNCTION audit_log_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            -- Direct UPDATE/DELETE is refused; deletes cascading from events (depth > 1) pass.
            IF TG_OP = 'UPDATE' OR pg_trigger_depth() < 2 THEN
                RAISE EXCEPTION 'audit_log is append-only';
            END IF;
            RETURN OLD;
        END;
        $$
        """
    )
    op.execute(
        "CREATE TRIGGER audit_log_append_only BEFORE UPDATE OR DELETE ON audit_log "
        "FOR EACH ROW EXECUTE FUNCTION audit_log_append_only()"
    )


def _disable_row_level_security() -> None:
    """Purpose: undo _enable_row_level_security (tables are dropped afterwards)."""
    op.execute("DROP TRIGGER IF EXISTS audit_log_append_only ON audit_log")
    op.execute("DROP FUNCTION IF EXISTS audit_log_append_only()")
    for policy, table in (
        ("events_admin_read", "events"),
        ("audit_log_admin", "audit_log"),
        ("jobs_dispatch_read", "jobs"),
        ("jobs_dispatch_update", "jobs"),
    ):
        op.execute(f"DROP POLICY IF EXISTS {policy} ON {table}")
    for table in EVENT_SCOPED_TABLES:
        op.execute(f"DROP POLICY IF EXISTS {table}_event_isolation ON {table}")
